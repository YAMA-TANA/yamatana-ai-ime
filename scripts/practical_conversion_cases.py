"""Non-numeric practical Japanese conversion cases for Mozc pipeline studies."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class CorpusCase:
    label: str
    category: str
    reading: str
    prefix: str
    suffix: str
    expected: str
    form: str


_cases: list[CorpusCase] = []


def pair(
    category: str,
    label: str,
    reading: str,
    expected: str,
    prefix: str,
    suffix: str,
    included_reading: str,
    included_expected: str,
    included_prefix: str,
    included_suffix: str,
) -> None:
    """Add one isolated target and one particle/inflection-inclusive target."""
    _cases.append(CorpusCase(f"{label}・単語", category, reading, prefix, suffix,
                             expected, "対象語のみ"))
    _cases.append(CorpusCase(f"{label}・助詞活用込み", category, included_reading,
                             included_prefix, included_suffix, included_expected,
                             "助詞・活用込み"))


