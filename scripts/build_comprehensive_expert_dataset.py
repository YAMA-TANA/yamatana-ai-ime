def build_expert_dataset() -> Path:
    base_file = ROOT / "integration" / "ime_combined_stress_train_30k.json"
    base_data = json.loads(base_file.read_text(encoding="utf-8")) if base_file.exists() else []

    generated: List[Dict[str, Any]] = []

    # 1. 異字同訓動詞ペア生成
    for group in VERB_PATTERNS:
        rd = group["reading"]
        pos = group["pos"]
        negs = group["negs"]
        for prefix, suffix in group["contexts"]:
            query = (
                f"文書方針: 自然で一般的な日本語として、文脈に合う表記を優先する。\n"
                f"文脈「{prefix}____{suffix}」に最も適切な表記を選びなさい。"
            )
            pos_doc = f"{prefix}{pos}{suffix}"
            for neg in negs:
                neg_doc = f"{prefix}{neg}{suffix}"
                # Over-sample to firmly establish lexical-context associations
                for _ in range(15):
                    generated.append({
                        "reading": rd,
                        "query": query,
                        "positive": pos_doc,
                        "negative": neg_doc,
                    })

    # 2. 推論・実装・ソフトウェア専門ペア生成
    for group in INFERENCE_IMPLEMENTATION_PATTERNS:
        rd = group["reading"]
        pos = group["pos"]
        negs = group["negs"]
        for prefix, suffix in group["contexts"]:
            query = (
                f"文書方針: IT・ソフトウェア文書として、技術用語、製品名、コード周辺の表記を優先する。\n"
                f"文脈「{prefix}____{suffix}」に最も適切な表記を選びなさい。"
            )
            pos_doc = f"{prefix}{pos}{suffix}"
            for neg in negs:
                neg_doc = f"{prefix}{neg}{suffix}"
                for _ in range(20):
                    generated.append({
                        "reading": rd,
                        "query": query,
                        "positive": pos_doc,
                        "negative": neg_doc,
                    })

    print(f"Generated {len(generated):,} targeted expert training pairs.")

    # 3. ホールドアウト120問との完全非重複確認
    holdout_file = ROOT / "build" / "holdout_120_evaluation.json"
    if holdout_file.exists():
        holdout_data = json.loads(holdout_file.read_text(encoding="utf-8"))
        holdout_sents = set()
        for d in holdout_data.get("details", []):
            holdout_sents.add(d["context"].replace("[", "").replace("]", ""))

        clean_generated = []
        filtered_count = 0
        for item in generated:
            if item["positive"] in holdout_sents or item["negative"] in holdout_sents:
                filtered_count += 1
            else:
                clean_generated.append(item)
        print(f"Verified against holdout set: {filtered_count} exact overlaps removed (Clean generated: {len(clean_generated):,})")
        generated = clean_generated

    # 4. Merge with base dataset
    combined = generated + base_data
    print(f"Total Expert Dataset Size: {len(combined):,} pairs.")

    out_file = ROOT / "integration" / "ime_expert_train.json"
    out_file.write_text(json.dumps(combined, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"[SUCCESS] Expert dataset written to: {out_file}")
    return out_file


if __name__ == "__main__":
    build_expert_dataset()
